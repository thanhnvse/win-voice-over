// Copies the OCR runtime out of node_modules into extension/vendor/, which the extension loads.
// MV3 forbids loading code from a CDN, so the worker and the WASM core must ship inside
// the extension. Run after `npm install`: `npm run vendor`.
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const modules = join(root, 'node_modules');
const vendor = join(root, 'extension', 'vendor');

const manifest = (pkg) => JSON.parse(readFileSync(join(modules, pkg, 'package.json'), 'utf8'));
const row = (pkg, note = '') => `| ${pkg}${note} | ${manifest(pkg).version} | ${manifest(pkg).license} |`;

const files = [
  ['tesseract.js/dist/tesseract.min.js', 'tesseract/tesseract.min.js'],
  ['tesseract.js/dist/worker.min.js', 'tesseract/worker.min.js'],
  ['tesseract.js/LICENSE.md', 'tesseract/LICENSE.md'],
  // The worker picks one of these at runtime depending on the CPU's SIMD support.
  // Only the LSTM-only builds are needed: the extension never loads the legacy engine.
  ['tesseract.js-core/tesseract-core-lstm.wasm.js', 'tesseract-core/tesseract-core-lstm.wasm.js'],
  ['tesseract.js-core/tesseract-core-simd-lstm.wasm.js', 'tesseract-core/tesseract-core-simd-lstm.wasm.js'],
  ['tesseract.js-core/tesseract-core-relaxedsimd-lstm.wasm.js', 'tesseract-core/tesseract-core-relaxedsimd-lstm.wasm.js'],
  ['tesseract.js-core/LICENSE', 'tesseract-core/LICENSE'],
  // Integer-quantised "best" model: about a third of the size of the float one.
  ['@tesseract.js-data/vie/4.0.0_best_int/vie.traineddata.gz', 'lang/vie.traineddata.gz'],
];

rmSync(vendor, { recursive: true, force: true });
for (const [from, to] of files) {
  const target = join(vendor, to);
  mkdirSync(dirname(target), { recursive: true });
  copyFileSync(join(modules, from), target);
}

writeFileSync(join(vendor, 'README.md'), `# Vendored OCR runtime

Generated by \`npm run vendor\`; do not edit by hand.

| Package | Version | License |
|---|---|---|
${row('tesseract.js')}
${row('tesseract.js-core')}
${row('@tesseract.js-data/vie', ' (4.0.0_best_int)')}
`);

console.log(`vendored ${files.length} files into ${vendor}`);
